"""Deterministic token materialization.

Input: a design decision (semantic intent). Output: a W3C DTCG token document plus
stack-specific emitters (CSS custom properties, Tailwind v4 @theme, shadcn :root/.dark,
Flutter ColorScheme/ThemeExtension). This is the 'contract' stage made mechanical: the
same decision always yields the same files, so output is reviewable and diffable.
"""
from __future__ import annotations

import json
from dataclasses import dataclass, field

__all__ = [
    "TokenSpec", "build_dtcg", "emit_css", "emit_tailwind_v4", "emit_shadcn",
    "emit_flutter", "emit_flutter_material", "emit_flutter_cupertino",
]

# A safe default scale so callers can pass a minimal spec and still get a full system.
_DEFAULT_SPACE = {"1": "4px", "2": "8px", "3": "12px", "4": "16px", "6": "24px", "8": "32px", "12": "48px"}
_DEFAULT_RADIUS = {"sm": "6px", "md": "10px", "lg": "14px", "full": "9999px"}
_DEFAULT_MOTION = {"fast": "150ms", "base": "200ms", "slow": "320ms"}
_DEFAULT_EASE = {"out": "cubic-bezier(0.22, 1, 0.36, 1)", "in-out": "cubic-bezier(0.65, 0, 0.35, 1)"}


@dataclass
class TokenSpec:
    """Semantic design decision. Colors are role->value maps for light and dark.

    Provide sRGB hex (so contrast is checkable); optionally include an OKLCH string that
    the emitters will prefer for the runtime value with the hex kept as a comment/fallback.
    """
    name: str
    light: dict[str, str]                 # role -> hex, e.g. {"bg":"#ffffff","fg":"#1a1a1a","brand":"#2f6bff"}
    dark: dict[str, str]
    oklch: dict[str, str] = field(default_factory=dict)  # role -> oklch() string (optional)
    space: dict[str, str] = field(default_factory=lambda: dict(_DEFAULT_SPACE))
    radius: dict[str, str] = field(default_factory=lambda: dict(_DEFAULT_RADIUS))
    motion: dict[str, str] = field(default_factory=lambda: dict(_DEFAULT_MOTION))
    ease: dict[str, str] = field(default_factory=lambda: dict(_DEFAULT_EASE))
    font: dict[str, str] = field(default_factory=lambda: {"display": "Space Grotesk, sans-serif", "sans": "Inter, sans-serif", "mono": "Geist Mono, monospace"})

    @staticmethod
    def from_dict(d: dict) -> "TokenSpec":
        return TokenSpec(
            name=d.get("name", "app"),
            light=d["light"], dark=d.get("dark", d["light"]),
            oklch=d.get("oklch", {}),
            space=d.get("space", dict(_DEFAULT_SPACE)),
            radius=d.get("radius", dict(_DEFAULT_RADIUS)),
            motion=d.get("motion", dict(_DEFAULT_MOTION)),
            ease=d.get("ease", dict(_DEFAULT_EASE)),
            font=d.get("font", {"display": "Space Grotesk, sans-serif", "sans": "Inter, sans-serif", "mono": "Geist Mono, monospace"}),
        )


def build_dtcg(spec: TokenSpec) -> dict:
    """Emit a W3C DTCG token document (color has light/dark modes as an extension)."""
    color = {}
    for role in spec.light:
        color[role] = {
            "$type": "color",
            "$value": spec.light[role],
            "$extensions": {"modes": {"light": spec.light[role], "dark": spec.dark.get(role, spec.light[role])}},
        }
    return {
        "$description": f"Design tokens for {spec.name} (generated by ultimate-ui-design MCP)",
        "color": color,
        "space": {k: {"$type": "dimension", "$value": v} for k, v in spec.space.items()},
        "radius": {k: {"$type": "dimension", "$value": v} for k, v in spec.radius.items()},
        "duration": {k: {"$type": "duration", "$value": v} for k, v in spec.motion.items()},
        "ease": {k: {"$type": "cubicBezier", "$value": v} for k, v in spec.ease.items()},
        "font": {k: {"$type": "fontFamily", "$value": v} for k, v in spec.font.items()},
    }


def _v(spec: TokenSpec, role: str, mode: str) -> str:
    src = spec.light if mode == "light" else spec.dark
    return src.get(role, spec.light.get(role, "#000000"))


def emit_css(spec: TokenSpec) -> str:
    """Framework-agnostic CSS custom properties with light + dark."""
    def block(mode):
        lines = [f"  --color-{r}: {_v(spec, r, mode)};" for r in spec.light]
        return "\n".join(lines)
    space = "\n".join(f"  --space-{k}: {v};" for k, v in spec.space.items())
    radius = "\n".join(f"  --radius-{k}: {v};" for k, v in spec.radius.items())
    dur = "\n".join(f"  --dur-{k}: {v};" for k, v in spec.motion.items())
    ease = "\n".join(f"  --ease-{k}: {v};" for k, v in spec.ease.items())
    font = "\n".join(f"  --font-{k}: {v};" for k, v in spec.font.items())
    return (
        ":root {\n  color-scheme: light dark;\n"
        f"{block('light')}\n{space}\n{radius}\n{dur}\n{ease}\n{font}\n}}\n\n"
        "@media (prefers-color-scheme: dark) {\n  :root {\n"
        f"{block('dark')}\n  }}\n}}\n"
    )


def emit_tailwind_v4(spec: TokenSpec) -> str:
    """Tailwind v4 CSS-first @theme block (generates bg-*/text-*/etc. utilities)."""
    colors = "\n".join(f"  --color-{r}: {_v(spec, r, 'light')};" for r in spec.light)
    radius = "\n".join(f"  --radius-{k}: {v};" for k, v in spec.radius.items())
    font = "\n".join(f"  --font-{k}: {v};" for k, v in spec.font.items())
    ease = "\n".join(f"  --ease-{k}: {v};" for k, v in spec.ease.items())
    return (
        '@import "tailwindcss";\n@custom-variant dark (&:is(.dark *));\n\n'
        f"@theme {{\n{colors}\n{radius}\n{font}\n{ease}\n}}\n"
    )


# shadcn expects this fixed semantic surface; map from provided roles with sane fallbacks.
_SHADCN_ROLES = [
    ("background", "bg"), ("foreground", "fg"), ("card", "bg"), ("card-foreground", "fg"),
    ("popover", "bg"), ("popover-foreground", "fg"), ("primary", "brand"),
    ("primary-foreground", "on-brand"), ("secondary", "muted"), ("secondary-foreground", "fg"),
    ("muted", "muted"), ("muted-foreground", "muted-fg"), ("accent", "accent"),
    ("accent-foreground", "fg"), ("destructive", "danger"), ("border", "border"),
    ("input", "border"), ("ring", "brand"),
]


def emit_shadcn(spec: TokenSpec) -> str:
    """shadcn/ui :root + .dark semantic variable blocks, sourced from spec roles."""
    def block(mode):
        out = []
        src = spec.light if mode == "light" else spec.dark
        for shad, role in _SHADCN_ROLES:
            val = src.get(role) or spec.light.get(role) or ("#ffffff" if "background" in shad or shad == "card" else "#111111")
            out.append(f"    --{shad}: {val};")
        out.append(f"    --radius: {spec.radius.get('md', '10px')};")
        return "\n".join(out)
    theme_inline = "\n".join(
        f"  --color-{shad}: var(--{shad});" for shad, _ in _SHADCN_ROLES
    )
    return (
        ":root {\n" + block("light") + "\n}\n\n.dark {\n" + block("dark") + "\n}\n\n"
        "@theme inline {\n" + theme_inline +
        "\n  --radius-sm: calc(var(--radius) - 4px);\n"
        "  --radius-md: calc(var(--radius) - 2px);\n"
        "  --radius-lg: var(--radius);\n}\n"
    )


def _hex_to_flutter(h: str) -> str:
    h = h.lstrip("#")
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    return f"0xFF{h.upper()}" if len(h) == 6 else "0xFF000000"


# ── shared Dart helpers for the platform-specific verticals ──────────────────
def _num(v: str) -> str:
    """'16px' / '14' -> '16.0' (a Dart double literal)."""
    n = "".join(c for c in str(v) if c.isdigit() or c == ".") or "0"
    return n if "." in n else f"{n}.0"


def _ms(v: str) -> str:
    """'200ms' -> '200' (integer milliseconds)."""
    return "".join(c for c in str(v) if c.isdigit()) or "0"


def _ident(key: str, prefix: str = "s") -> str:
    """Dart identifier from a token key; digit-leading keys get a letter prefix."""
    k = key.replace("-", "_")
    return f"{prefix}{k}" if k[:1].isdigit() else k


def _dart_scaffold(spec: TokenSpec, touch_target: float) -> str:
    """Deterministic spacing/radius/duration/touch constants shared by both verticals.

    These replace raw numbers in widgets — the mobile analogue of CSS custom properties.
    Values come straight from the spec's scales (8-pt grid preserved), so output is diffable.
    """
    space = "\n".join(f"  static const double {_ident(k)} = {_num(v)};" for k, v in spec.space.items())
    radius = "\n".join(f"  static const double {_ident(k, 'r')} = {_num(v)};" for k, v in spec.radius.items())
    dur = "\n".join(
        f"  static const {_ident(k, 'd')} = Duration(milliseconds: {_ms(v)});" for k, v in spec.motion.items()
    )
    return (
        f"/// 8-pt grid spacing (widgets read these; they never inline numbers).\n"
        f"abstract final class AppSpacing {{\n{space}\n}}\n\n"
        f"abstract final class AppRadius {{\n{radius}\n}}\n\n"
        f"abstract final class AppDurations {{\n{dur}\n}}\n\n"
        f"/// Platform minimum hit target - enforce on every interactive widget.\n"
        f"abstract final class AppMinTarget {{\n  static const double touch = {touch_target};\n}}\n"
    )


def _dart_token_fields(spec: TokenSpec) -> tuple[str, str, str, str]:
    """(field declarations, ctor params, light initializers, dark initializers) for semantic roles."""
    fields = "\n".join(f"  final Color {_ident(r, 'c_')};" for r in spec.light)
    ctor = ", ".join(f"required this.{_ident(r, 'c_')}" for r in spec.light)
    light = ", ".join(f"{_ident(r, 'c_')}: const Color({_hex_to_flutter(spec.light[r])})" for r in spec.light)
    dark = ", ".join(
        f"{_ident(r, 'c_')}: const Color({_hex_to_flutter(spec.dark.get(r, spec.light[r]))})" for r in spec.light
    )
    return fields, ctor, light, dark


def emit_flutter_material(spec: TokenSpec) -> str:
    """Android vertical — Material 3. Seeded ColorScheme with spec roles pinned, 8-dp grid,
    48-dp touch floor, and a ThemeExtension for semantic tokens. `AppTheme.light()/.dark()`
    return ready-to-use `ThemeData(useMaterial3: true)`."""
    fields, ctor, light, dark = _dart_token_fields(spec)
    seed_l = _hex_to_flutter(spec.light.get("brand", "#2f6bff"))
    seed_d = _hex_to_flutter(spec.dark.get("brand", spec.light.get("brand", "#5b8bff")))

    return (
        "import 'package:flutter/material.dart';\n\n"
        "// Material 3 (Android) theme - generated by ultimate-ui-design MCP.\n"
        "// Theme.of(context) IS the token source; no Color(0x..) literals in widgets.\n\n"
        f"{_dart_scaffold(spec, 48.0)}\n\n"
        "@immutable\nclass AppTokens extends ThemeExtension<AppTokens> {\n"
        f"{fields}\n  const AppTokens({{{ctor}}});\n\n"
        f"  static const light = AppTokens({light});\n"
        f"  static const dark = AppTokens({dark});\n\n"
        "  @override AppTokens copyWith() => this;\n"
        "  @override AppTokens lerp(ThemeExtension<AppTokens>? other, double t) => this;\n}\n\n"
        "abstract final class AppTheme {\n"
        f"  static const _seedLight = Color({seed_l});\n"
        f"  static const _seedDark = Color({seed_d});\n\n"
        "  static ColorScheme _scheme(Brightness b) =>\n"
        "      (b == Brightness.light\n"
        "              ? ColorScheme.fromSeed(seedColor: _seedLight, brightness: Brightness.light)\n"
        "              : ColorScheme.fromSeed(seedColor: _seedDark, brightness: Brightness.dark))\n"
        "          .copyWith(\n"
        "%LIGHT_OR_DARK%"
        "          );\n\n"
        "  static ThemeData light() => _build(Brightness.light, AppTokens.light);\n"
        "  static ThemeData dark() => _build(Brightness.dark, AppTokens.dark);\n\n"
        "  static ThemeData _build(Brightness b, AppTokens tokens) => ThemeData(\n"
        "        useMaterial3: true,\n"
        "        colorScheme: _scheme(b),\n"
        "        extensions: [tokens],\n"
        "      );\n}\n"
    ).replace(
        "%LIGHT_OR_DARK%",
        "            // spec roles pinned over the generated tonal palette\n"
        "            primary: b == Brightness.light\n"
        f"                ? const Color({_hex_to_flutter(spec.light.get('brand', '#2f6bff'))})\n"
        f"                : const Color({_hex_to_flutter(spec.dark.get('brand', spec.light.get('brand', '#5b8bff')))}),\n"
        "            surface: b == Brightness.light\n"
        f"                ? const Color({_hex_to_flutter(spec.light.get('bg', '#ffffff'))})\n"
        f"                : const Color({_hex_to_flutter(spec.dark.get('bg', spec.light.get('bg', '#0b0c0e')))}),\n"
        "            onSurface: b == Brightness.light\n"
        f"                ? const Color({_hex_to_flutter(spec.light.get('fg', '#111111'))})\n"
        f"                : const Color({_hex_to_flutter(spec.dark.get('fg', spec.light.get('fg', '#fafafa')))}),\n",
    )


def emit_flutter_cupertino(spec: TokenSpec) -> str:
    """iOS vertical — Cupertino/HIG. CupertinoThemeData (light/dark), 44-pt touch floor,
    and an AppTokensScope InheritedWidget carrying semantic roles (Cupertino has no
    ThemeExtension). `AppTheme.light()/.dark()` return ready-to-use `CupertinoThemeData`."""
    fields, ctor, light, dark = _dart_token_fields(spec)

    def theme(mode, brightness):
        src = spec.light if mode == "light" else spec.dark
        return (
            f"  static const {mode} = CupertinoThemeData(\n"
            f"    brightness: Brightness.{brightness},\n"
            f"    primaryColor: Color({_hex_to_flutter(src.get('brand', '#2f6bff'))}),\n"
            f"    scaffoldBackgroundColor: Color({_hex_to_flutter(src.get('bg', '#ffffff'))}),\n"
            f"    barBackgroundColor: Color({_hex_to_flutter(src.get('bg', '#ffffff'))}),\n"
            f"    textTheme: CupertinoTextThemeData(\n"
            f"      primaryColor: Color({_hex_to_flutter(src.get('fg', '#111111'))}),\n"
            f"    ),\n"
            f"  );"
        )

    return (
        "import 'package:flutter/cupertino.dart';\n\n"
        "// Cupertino (iOS / Human Interface Guidelines) theme - generated by ultimate-ui-design MCP.\n"
        "// Use continuous corners (BorderRadius via SmoothRectangleBorder or superellipse) and\n"
        "// prefer semantic CupertinoColors where a role adapts automatically.\n\n"
        f"{_dart_scaffold(spec, 44.0)}\n\n"
        "@immutable\nclass AppTokens {\n"
        f"{fields}\n  const AppTokens({{{ctor}}});\n\n"
        f"  static const light = AppTokens({light});\n"
        f"  static const dark = AppTokens({dark});\n}}\n\n"
        "/// Cupertino has no ThemeExtension; expose semantic tokens via an InheritedWidget.\n"
        "class AppTokensScope extends InheritedWidget {\n"
        "  final AppTokens tokens;\n"
        "  const AppTokensScope({super.key, required this.tokens, required super.child});\n"
        "  static AppTokens of(BuildContext context) =>\n"
        "      context.dependOnInheritedWidgetOfExactType<AppTokensScope>()!.tokens;\n"
        "  @override\n"
        "  bool updateShouldNotify(AppTokensScope oldWidget) => tokens != oldWidget.tokens;\n}\n\n"
        "abstract final class AppTheme {\n"
        f"{theme('light','light')}\n\n{theme('dark','dark')}\n}}\n"
    )


def emit_flutter(spec: TokenSpec) -> str:
    """Flutter: a ColorScheme-ish seed + a ThemeExtension carrying semantic tokens."""
    def scheme(mode, brightness):
        src = spec.light if mode == "light" else spec.dark
        brand = src.get("brand", "#2f6bff")
        bg = src.get("bg", "#ffffff")
        fg = src.get("fg", "#111111")
        return (
            f"  static const {mode}Scheme = ColorScheme(\n"
            f"    brightness: Brightness.{brightness},\n"
            f"    primary: Color({_hex_to_flutter(brand)}),\n"
            f"    onPrimary: Color({_hex_to_flutter(src.get('on-brand', '#ffffff'))}),\n"
            f"    surface: Color({_hex_to_flutter(bg)}),\n"
            f"    onSurface: Color({_hex_to_flutter(fg)}),\n"
            f"    error: Color({_hex_to_flutter(src.get('danger', '#d92d20'))}),\n"
            f"    onError: Color(0xFFFFFFFF),\n"
            f"    secondary: Color({_hex_to_flutter(src.get('accent', brand))}),\n"
            f"    onSecondary: Color(0xFFFFFFFF),\n"
            f"  );"
        )
    ext_fields = "\n".join(
        f"  final Color {r.replace('-', '_')};" for r in spec.light
    )
    ext_ctor = ", ".join(f"required this.{r.replace('-', '_')}" for r in spec.light)
    ext_light = ", ".join(f"{r.replace('-', '_')}: const Color({_hex_to_flutter(spec.light[r])})" for r in spec.light)
    ext_dark = ", ".join(f"{r.replace('-', '_')}: const Color({_hex_to_flutter(spec.dark.get(r, spec.light[r]))})" for r in spec.light)
    return (
        "import 'package:flutter/material.dart';\n\n"
        f"class AppColors {{\n{scheme('light','light')}\n\n{scheme('dark','dark')}\n}}\n\n"
        "@immutable\nclass AppTokens extends ThemeExtension<AppTokens> {\n"
        f"{ext_fields}\n  const AppTokens({{{ext_ctor}}});\n\n"
        f"  static const light = AppTokens({ext_light});\n"
        f"  static const dark = AppTokens({ext_dark});\n\n"
        "  @override AppTokens copyWith() => this;\n"
        "  @override AppTokens lerp(ThemeExtension<AppTokens>? other, double t) => this;\n}\n"
    )
